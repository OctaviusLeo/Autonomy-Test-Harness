"""The derived Nav2 parameter file differs from the stock one in exactly the four lidar topics (Req 0.10, 4.1)."""

from __future__ import annotations

import pytest
import yaml

from harness import nav2_params

MINI_STOCK = """amcl:
  ros__parameters:
    scan_topic: scan
local_costmap:
  local_costmap:
    ros__parameters:
      plugins: ["voxel_layer"]
      voxel_layer:
        observation_sources: scan
        scan:
          topic: /scan
global_costmap:
  global_costmap:
    ros__parameters:
      obstacle_layer:
        scan:
          topic: /scan
collision_monitor:
  ros__parameters:
    observation_sources: ["scan"]
    scan:
      type: "scan"
      topic: "scan"
    # a comment
    polygons:
      - "x"
"""


def test_committed_files_differ_only_in_the_four_topics(repo_root):
    stock = yaml.safe_load((repo_root / "docs" / "evidence" / "nav2_params_stock.yaml").read_text())
    derived = yaml.safe_load((repo_root / "config" / "nav2_params_ath.yaml").read_text())
    diff = nav2_params.value_diff(stock, derived)
    assert set(diff) == set(nav2_params.SCAN_TOPIC_PATHS)
    for old, new in diff.values():
        assert old in ("scan", "/scan") and new == "/scan_ath"
    assert nav2_params.remaining_scan_refs(derived) == []


def test_retarget_keeps_everything_else_byte_for_byte():
    derived = nav2_params.retarget_text(MINI_STOCK)
    changed = [(a, b) for a, b in zip(MINI_STOCK.splitlines(), derived.splitlines()) if a != b]
    assert changed == [
        ("    scan_topic: scan", "    scan_topic: /scan_ath"),
        ("          topic: /scan", "          topic: /scan_ath"),
        ("          topic: /scan", "          topic: /scan_ath"),
        ('      topic: "scan"', '      topic: "/scan_ath"'),
    ]
    nav2_params.check(MINI_STOCK, derived)


def test_missing_path_and_unexpected_value_are_errors():
    with pytest.raises(ValueError, match="lacks"):
        nav2_params.retarget_text(MINI_STOCK.replace("scan_topic: scan", "other: scan"))
    with pytest.raises(ValueError, match="expected one of"):
        nav2_params.retarget_text(MINI_STOCK.replace("scan_topic: scan", "scan_topic: lidar"))


def test_check_rejects_extra_differences():
    derived = nav2_params.retarget_text(MINI_STOCK).replace('type: "scan"', 'type: "pointcloud"')
    with pytest.raises(ValueError, match="unexpected differences"):
        nav2_params.check(MINI_STOCK, derived)


def test_check_rejects_a_remaining_raw_scan_reader():
    stock = MINI_STOCK + "docking:\n  ros__parameters:\n    topic: /scan\n"
    with pytest.raises(ValueError, match="still reads"):
        nav2_params.check(stock, nav2_params.retarget_text(stock))


def test_make_writes_derived_file_and_stock_copy(tmp_path, load_script):
    share = tmp_path / "share"
    (share / "params").mkdir(parents=True)
    (share / "params" / "nav2_params.yaml").write_text(MINI_STOCK)
    (share / "package.xml").write_text("<package><version>9.9.9</version></package>")
    script = load_script("make_nav2_params")
    assert script.main(["--out-dir", str(tmp_path / "out"), "--share-dir", str(share)]) == 0
    derived = (tmp_path / "out" / "config" / "nav2_params_ath.yaml").read_text()
    assert derived.startswith("# Generated by scripts/make_nav2_params.py from nav2_bringup 9.9.9")
    assert (tmp_path / "out" / "docs" / "evidence" / "nav2_params_stock.yaml").read_text() == MINI_STOCK
    (share / "package.xml").write_text("<package/>")
    assert nav2_params.package_version(share) == "unknown"
