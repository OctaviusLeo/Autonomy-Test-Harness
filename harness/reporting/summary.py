"""Markdown Summary_Report (Requirements 7.2-7.5).

It states the pass rate per Fault type (``none`` for no Fault), lists every failed or errored run with its
reason and detail, links each one's ROS_Bag, and gives the exact ``scripts/rerun_one.sh`` command with
the Scenario's seed. It ends with the stamp (command, seed, commit). Bag links are host paths, or, when
``bag_link_base`` is given (Jenkins), that base followed by the bag's path relative to the run directory.
The file is generated, never hand-edited; inputs are validated first and the file is written atomically.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Iterable

from harness.reporting.records import outcome, validate_records, write_atomic


def rerun_command(record: dict[str, Any]) -> str:
    config = record.get("generator_config") or "<generator config of the set>"
    command = f"bash scripts/rerun_one.sh --config {config} --seed {record['seed']}"
    if record["fault_condition"] != "none":
        command += f" --condition {record['fault_condition']}"
    return command


def bag_link(record: dict[str, Any], bag_link_base: str | None = None, run_root: str | None = None) -> str:
    bag = str(record.get("bag_path") or "")
    if bag_link_base and run_root and bag.startswith(run_root.rstrip("/") + "/"):
        bag = bag_link_base.rstrip("/") + "/" + bag[len(run_root.rstrip("/")) + 1:]
    return f"[bag]({bag})"


def pass_rates(records: list[dict[str, Any]]) -> list[tuple[str, int, int, float]]:
    by_condition: dict[str, list[dict[str, Any]]] = {}
    for r in records:
        by_condition.setdefault(r["fault_condition"], []).append(r)
    rows = []
    for condition, rs in by_condition.items():
        passed = sum(1 for r in rs if outcome(r) == "pass")
        rows.append((condition, len(rs), passed, passed / len(rs)))
    return rows


def _cell(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def summary_markdown(records: Iterable[dict[str, Any]], title: str, stamp: dict[str, Any],
                     bag_link_base: str | None = None, run_root: str | None = None,
                     sources: Iterable[str] | None = None) -> str:
    records = validate_records(records, sources)
    lines = [f"# {title}", "", "Generated by the harness from the RunRecords; do not edit by hand.", "",
             "## Pass rate per Fault type", "", "| Fault type | Runs | Passed | Pass rate |", "| --- | --- | --- | --- |"]
    for condition, n, passed, rate in pass_rates(records):
        lines.append(f"| {condition} | {n} | {passed} | {rate:.3f} |")
    failed = [r for r in records if outcome(r) != "pass"]
    lines += ["", f"## Failed runs ({len(failed)})", ""]
    if failed:
        lines += ["| Scenario | Fault type | Outcome | Reason | Detail | Bag | Re-run |",
                  "| --- | --- | --- | --- | --- | --- | --- |"]
        for r in failed:
            result = outcome(r)
            reason = f"errored: {r.get('failing_step')}" if result == "errored" else r["verdict"]["reason"]
            detail = r.get("effect") if result == "errored" else r["verdict"].get("detail")
            lines.append(f"| {r['scenario_id']} | {r['fault_condition']} | {result} | {_cell(reason)} | "
                         f"{_cell(detail)} | {bag_link(r, bag_link_base, run_root)} | `{rerun_command(r)}` |")
    else:
        lines.append("None.")
    lines += ["", "## Stamp", "", f"- Command: `{stamp['command']}`", f"- Seed: {stamp['seed']}",
              f"- Commit: `{stamp['commit']}`", ""]
    return "\n".join(lines)


def write_summary(records: Iterable[dict[str, Any]], path: str | Path, title: str, stamp: dict[str, Any],
                  bag_link_base: str | None = None, run_root: str | None = None,
                  sources: Iterable[str] | None = None) -> Path:
    return write_atomic(path, summary_markdown(records, title, stamp, bag_link_base, run_root, sources))
