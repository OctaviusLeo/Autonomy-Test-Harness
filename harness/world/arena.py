"""The ``empty_10x10`` arena: one definition for the Gazebo world, the Nav2 map, and the wall shapes.

The free interior spans x and y from -5.0 to 5.0 m, enclosed by four walls 0.2 m thick and 1.0 m
high. The map covers -5.5 to 5.5 m at 0.05 m (220 x 220 cells) with origin (-5.5, -5.5), so map
coordinates equal Gazebo world coordinates: Ground_Truth, Scenario poses, and AMCL share one frame
(Requirement 2.6). The Generator and the Oracle use :attr:`Arena.walls` as obstacle shapes, so all
three consumers agree by construction.
"""

from __future__ import annotations

import dataclasses
from pathlib import Path

SUPPORTED_WORLDS = ("empty_10x10",)

INTERIOR_HALF_M = 5.0
WALL_THICKNESS_M = 0.2
WALL_HEIGHT_M = 1.0
MAP_HALF_M = 5.5
MAP_RESOLUTION_M = 0.05
FREE = 254
OCCUPIED = 0


@dataclasses.dataclass(frozen=True)
class Rect:
    """An oriented rectangle footprint: center, full extents along its own axes, yaw (radians)."""

    x: float
    y: float
    size_x: float
    size_y: float
    yaw: float = 0.0


@dataclasses.dataclass(frozen=True)
class Circle:
    """A circular footprint: center and radius."""

    x: float
    y: float
    radius: float


Shape = Rect | Circle


@dataclasses.dataclass(frozen=True)
class Arena:
    world_id: str
    interior_half_m: float
    map_half_m: float
    resolution_m: float
    walls: tuple[Rect, ...]

    @property
    def map_cells(self) -> int:
        return int(round(2 * self.map_half_m / self.resolution_m))

    @property
    def map_origin(self) -> tuple[float, float]:
        return (-self.map_half_m, -self.map_half_m)

    def cell_center(self, i: int, j: int) -> tuple[float, float]:
        """World coordinates of the center of map cell (column i, row j from the bottom)."""
        ox, oy = self.map_origin
        return (ox + (i + 0.5) * self.resolution_m, oy + (j + 0.5) * self.resolution_m)

    def is_interior(self, x: float, y: float) -> bool:
        return abs(x) < self.interior_half_m and abs(y) < self.interior_half_m


def _walls(half: float, thickness: float) -> tuple[Rect, ...]:
    center = half + thickness / 2
    span = 2 * (half + thickness)
    return (
        Rect(0.0, center, span, thickness),     # north (covers both corners)
        Rect(0.0, -center, span, thickness),    # south
        Rect(center, 0.0, thickness, 2 * half),  # east
        Rect(-center, 0.0, thickness, 2 * half),  # west
    )


def arena(world_id: str = "empty_10x10") -> Arena:
    if world_id not in SUPPORTED_WORLDS:
        raise ValueError(f"unsupported world {world_id!r}; supported: {', '.join(SUPPORTED_WORLDS)}")
    return Arena(
        world_id=world_id,
        interior_half_m=INTERIOR_HALF_M,
        map_half_m=MAP_HALF_M,
        resolution_m=MAP_RESOLUTION_M,
        walls=_walls(INTERIOR_HALF_M, WALL_THICKNESS_M),
    )


def map_grid(a: Arena) -> list[list[int]]:
    """Occupancy values by row from the bottom (j) then column (i): interior free, everything else occupied."""
    n = a.map_cells
    grid = []
    for j in range(n):
        row = []
        for i in range(n):
            x, y = a.cell_center(i, j)
            row.append(FREE if a.is_interior(x, y) else OCCUPIED)
        grid.append(row)
    return grid


def write_map(a: Arena, pgm_path: str | Path, yaml_path: str | Path) -> None:
    """Write the map as a binary PGM (top row = largest y) and its map_server YAML."""
    pgm_path, yaml_path = Path(pgm_path), Path(yaml_path)
    grid = map_grid(a)
    n = a.map_cells
    header = f"P5\n# {a.world_id} generated by scripts/build_world.py\n{n} {n}\n255\n".encode("ascii")
    body = bytes(v for row in reversed(grid) for v in row)
    pgm_path.parent.mkdir(parents=True, exist_ok=True)
    pgm_path.write_bytes(header + body)
    ox, oy = a.map_origin
    yaml_path.write_text(
        f"# {a.world_id} map, generated by scripts/build_world.py; map frame == world frame\n"
        f"image: {pgm_path.name}\n"
        "mode: trinary\n"
        f"resolution: {a.resolution_m}\n"
        f"origin: [{ox}, {oy}, 0.0]\n"
        "negate: 0\n"
        "occupied_thresh: 0.65\n"
        "free_thresh: 0.25\n",
        encoding="utf-8",
    )


def read_pgm(path: str | Path) -> tuple[int, int, bytes]:
    """Read a binary PGM written by :func:`write_map`: (width, height, pixel bytes top row first)."""
    data = Path(path).read_bytes()
    tokens: list[bytes] = []
    pos = 0
    while len(tokens) < 4:
        while data[pos:pos + 1].isspace():
            pos += 1
        if data[pos:pos + 1] == b"#":
            pos = data.index(b"\n", pos) + 1
            continue
        end = pos
        while not data[end:end + 1].isspace():
            end += 1
        tokens.append(data[pos:end])
        pos = end
    if tokens[0] != b"P5":
        raise ValueError(f"{path}: not a binary PGM")
    width, height = int(tokens[1]), int(tokens[2])
    return width, height, data[pos + 1:pos + 1 + width * height]


def _wall_link(k: int, wall: Rect, height: float) -> str:
    geometry = f"<box><size>{wall.size_x} {wall.size_y} {height}</size></box>"
    return f"""    <model name="wall_{k}">
      <static>true</static>
      <pose>{wall.x} {wall.y} {height / 2} 0 0 {wall.yaw}</pose>
      <link name="link">
        <collision name="collision"><geometry>{geometry}</geometry></collision>
        <visual name="visual">
          <geometry>{geometry}</geometry>
          <material><ambient>0.6 0.6 0.6 1</ambient><diffuse>0.6 0.6 0.6 1</diffuse></material>
        </visual>
      </link>
    </model>
"""


def world_sdf(a: Arena) -> str:
    """The Gazebo world: the stock world's systems plus SceneBroadcaster, a ground plane, and the walls."""
    walls = "".join(_wall_link(k, w, WALL_HEIGHT_M) for k, w in enumerate(a.walls))
    return f"""<?xml version="1.0"?>
<!-- {a.world_id}: generated by scripts/build_world.py from harness/world/arena.py; do not edit. -->
<sdf version="1.6" xmlns:xacro="http://www.ros.org/wiki/xacro">
  <!-- Declared because tb4_simulation_launch.py runs every world through xacro with headless:=...;
       unlike the stock depot.sdf, SceneBroadcaster loads either way (the Ground_Truth pose stream). -->
  <xacro:arg name="headless" default="true"/>
  <world name="{a.world_id}">
    <physics name="1ms" type="ode">
      <max_step_size>0.003</max_step_size>
      <real_time_update_rate>1000.0</real_time_update_rate>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <scene>
      <ambient>1.0 1.0 1.0</ambient>
      <background>0.8 0.8 0.8</background>
      <grid>false</grid>
    </scene>
    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.8 0.8 0.8 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.1 -0.9</direction>
    </light>
    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>{2 * a.map_half_m} {2 * a.map_half_m}</size></plane></geometry>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>{2 * a.map_half_m} {2 * a.map_half_m}</size></plane></geometry>
          <material><ambient>0.8 0.8 0.8 1</ambient><diffuse>0.8 0.8 0.8 1</diffuse></material>
        </visual>
      </link>
    </model>
{walls}  </world>
</sdf>
"""


def write_world_sdf(a: Arena, path: str | Path) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(world_sdf(a), encoding="utf-8")


def obstacle_shape(obstacle) -> Shape:
    """Footprint of a Scenario obstacle (a schema BoxObstacle or CylinderObstacle)."""
    if obstacle.shape == "box":
        return Rect(obstacle.pose.x, obstacle.pose.y, obstacle.size.x, obstacle.size.y, obstacle.pose.yaw)
    if obstacle.shape == "cylinder":
        return Circle(obstacle.pose.x, obstacle.pose.y, obstacle.size.radius)
    raise ValueError(f"unknown obstacle shape {obstacle.shape!r}")
